function summarize_port250()
%SUMMARIZE_PORT250 Tables + figure comparing the 250 Hz port with 4096 Hz.
%   Reads analysis/results/{gate_fs4096,port_*}.mat; writes
%   analysis250/results/summary_250_vs_4096.md and port250_comparison.png.
here = fileparts(mfilename('fullpath'));
rdir = fullfile(fileparts(here), 'analysis', 'results');
odir = fullfile(here, 'results'); if ~exist(odir, 'dir'), mkdir(odir); end
L = @(t) load(fullfile(rdir, [t '.mat']));

conds = {
  'gate_fs4096',      '4096 Hz, original trigger (shipped model, rebuilt)'
  'port_4096n',       '4096 Hz, nearest-sample trigger'
  'port_4096n_noart', '4096 Hz, nearest-sample, no artifact'
  'port_250orig',     '250 Hz, original trigger (±0.02 rad)'
  'port_250n',        '250 Hz, nearest-sample trigger'
  'port_250n_noart',  '250 Hz, nearest-sample, no artifact'
  'port_250p',        '250 Hz, predict trigger (1-sample lead)'
  'port_250p_noart',  '250 Hz, predict trigger, no artifact'
  'port_250n_ideal',  '250 Hz, nearest-sample, ideal (zero-phase) anti-alias'
};
fid = fopen(fullfile(odir, 'summary_250_vs_4096.md'), 'w'); c = onCleanup(@() fclose(fid));
fprintf(fid, '# PLDBS pipeline at 250 Hz vs 4096 Hz (STN beta, dataset1)\n\n');
fprintf(fid, 'Generated by `analysis250/summarize_port250.m`; all numbers from the sweeps. NRO, mean ± SD over 8 target phases. 250 Hz runs use a 28 ms (7-sample) Kalman window unless stated; 4096 Hz runs use the shipped 12 ms. **ref** = model''s own bandpass on the clean signal (paper-style); **zp** = zero-phase Hilbert phase of the original 4096 Hz recording at each pulse''s true time.\n\n');

fprintf(fid, '## Phase locking (NRO)\n\n| Condition | pulses/s | ref bias | ref std | ref ±30° | ref ±45° | ref ±90° | ref ±30° amp>2 | zp std | zp ±90° |\n|---|---|---|---|---|---|---|---|---|---|\n');
T = struct();
for k = 1:size(conds, 1)
    S = L(conds{k,1}); mm = [S.M(strcmp({S.M.name}, 'NRO')).m]; T.(conds{k,1}) = mm;
    r = [mm.ref]; z = [mm.zp]; A = vertcat(r.acc); A2 = vertcat(r.acc_amp2); Z = vertcat(z.acc); t = mm(1).tols;
    fprintf(fid, '| %s | %.1f | %.1f° ± %.1f° | %.1f° ± %.1f° | %.1f%% | %.1f%% | %.1f%% | %.1f%% | %.0f° | %.1f%% |\n', conds{k,2}, ...
        mean([mm.rate_Hz]), mean([r.bias]), std([r.bias]), mean([r.std]), std([r.std]), 100*mean(A(:,t==30)), ...
        100*mean(A(:,t==45)), 100*mean(A(:,t==90)), 100*mean(A2(:,t==30)), mean([z.std]), 100*mean(Z(:,t==90)));
end
fprintf(fid, '\nPaper (4096 Hz simulation, NRO): bias 9.55° ± 6.12°, std 20.58° ± 2.14°, 93.24%% within ±45°. Chance level for ±90° is 50%%.\n\n');

fprintf(fid, '## Estimators (ref, 8 targets)\n\n| Estimator | 4096 Hz bias | 4096 Hz std | 4096 Hz ±45° | 250 Hz bias | 250 Hz std | 250 Hz ±45° |\n|---|---|---|---|---|---|---|\n');
S4 = L('port_4096n'); S2 = L('port_250n');
for nm = {'NRO', 'ZC', 'arHT'}
    a = [S4.M(strcmp({S4.M.name}, nm{1})).m]; b = [S2.M(strcmp({S2.M.name}, nm{1})).m];
    ra = [a.ref]; rb = [b.ref]; Aa = vertcat(ra.acc); Ab = vertcat(rb.acc); t = a(1).tols;
    fprintf(fid, '| %s | %.1f° | %.1f° | %.1f%% | %.1f° | %.1f° | %.1f%% |\n', nm{1}, mean([ra.bias]), mean([ra.std]), ...
        100*mean(Aa(:,t==45)), mean([rb.bias]), mean([rb.std]), 100*mean(Ab(:,t==45)));
end
fprintf(fid, '\narHT windows were re-tuned for 250 Hz (buffer 256 ms, AR order 8, Hilbert 128 ms, edge 32 ms); the 4096 Hz arHT uses the shipped settings.\n\n');

fprintf(fid, '## Artifact suppression vs. Kalman window (target 135° model conv.)\n\nBeta spectral-amplitude error vs. artifact-free signal (time-domain envelope error in parentheses).\n\n| fs | window | Kalman | blank + interp | sample-hold | zeroing | NRO ref std | ref ±45° |\n|---|---|---|---|---|---|---|---|\n');
for S = {S4, S2}
    W = S{1}.W; fsx = S{1}.cfg.fs;
    for i = 1:numel(W)
        a = W(i).m.art; r = W(i).m.ref;
        fprintf(fid, '| %d | %d ms (%d smp) | %.1f%% (%.1f%%) | %.1f%% (%.1f%%) | %.1f%% (%.1f%%) | %.1f%% (%.1f%%) | %.1f° | %.1f%% |\n', ...
            fsx, W(i).width_ms, a.width_samples, 100*a.spec.kalman, 100*a.env.kalman, 100*a.spec.blank, 100*a.env.blank, ...
            100*a.spec.hold, 100*a.env.hold, 100*a.spec.zero, 100*a.env.zero, r.std, 100*r.acc(W(i).m.tols==45));
    end
end

% ---- figure ----
fig = figure('Visible', 'off', 'Position', [0 0 1300 400]);
subplot(1,3,1); hold on;
cols = {[.2 .4 .7], [.85 .4 .1], [.3 .6 .3]};
keys = {'port_4096n', 'port_250n', 'port_250p'}; labs = {'4096 Hz', '250 Hz nearest', '250 Hz predict'};
for k = 1:3
    c = arrayfun(@(m) m.ref.err_deg(:), T.(keys{k}), 'uni', 0); e = vertcat(c{:});
    histogram(e, -180:10:180, 'Normalization', 'probability', 'DisplayStyle', 'stairs', 'EdgeColor', cols{k}, 'LineWidth', 1.5);
end
legend(labs, 'Location', 'northwest'); xlabel('phase error vs ref (deg)'); ylabel('fraction of pulses'); title('NRO, all 8 targets (ref)');
subplot(1,3,2); hold on;
for k = 1:3
    c = arrayfun(@(m) m.zp.err_deg(:), T.(keys{k}), 'uni', 0); e = vertcat(c{:});
    histogram(e, -180:20:180, 'Normalization', 'probability', 'DisplayStyle', 'stairs', 'EdgeColor', cols{k}, 'LineWidth', 1.5);
end
yline(20/360, 'k:'); xlabel('phase error vs zero-phase truth (deg)'); title('Same pulses vs true phase (zp)');
subplot(1,3,3);
W = S2.W; w = [W.width_ms]; a = [W.m]; a = [a.art]; sp = [a.spec];
semilogy(w, 100*[sp.kalman], 'o-', w, 100*[sp.blank], 's-', w, 100*[sp.hold], '^-', w, 100*[sp.zero], 'd-');
xline(28, 'k:'); legend('Kalman', 'blank+interp', 'hold', 'zero'); xlabel('blanking window (ms) at 250 Hz'); ylabel('beta spectral error (%)');
title('Artifact suppression at 250 Hz');
exportgraphics(fig, fullfile(odir, 'port250_comparison.png'), 'Resolution', 120); close(fig);
fprintf('Wrote %s\n', fullfile(odir, 'summary_250_vs_4096.md'));
end
